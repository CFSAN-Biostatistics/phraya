#!/usr/bin/env python3
"""
Compute placement accuracy (PA) for phraya protein-mode alignment from
.phraya.queries + gen_synthetic_protein.py's own truth sidecar (ADR-0013).

Unlike phraya_accuracy.py (DNA, wgsim/dwgsim read-name-encoded truth), there is
no external protein read simulator to defer truth-encoding to — protein targets
are generated by gen_synthetic_protein.py, which writes an explicit
`<queries>.truth.tsv` sidecar (query_id, source_protein, start, n_subs,
indel_events) instead of packing truth into the FASTA header. This script reads
that sidecar directly rather than regex-parsing a read name.

PA = (correctly placed queries) / (placed, truth-matched queries), where
"correctly placed" means the best-scoring alignment's target position is within
<tolerance> residues of the query's true `start` in its source protein.

Usage:
    phraya_accuracy_protein.py <file.phraya.queries> --truth <queries.fa.truth.tsv> [--tolerance 10] [--total-queries N]

Outputs tab-separated to stdout:
    pa  n_mapped  n_correct  n_unaligned  unaligned_frac
"""
import argparse
import sys

import msgpack
import zstandard


def load_truth(path: str) -> dict[str, int]:
    """Returns {query_id: true_start} from gen_synthetic_protein.py's truth.tsv."""
    truth = {}
    with open(path) as fh:
        header = fh.readline().rstrip("\n").split("\t")
        id_col = header.index("query_id")
        start_col = header.index("start")
        for line in fh:
            fields = line.rstrip("\n").split("\t")
            truth[fields[id_col]] = int(fields[start_col])
    return truth


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("queries_file")
    parser.add_argument("--truth", required=True, help="gen_synthetic_protein.py .truth.tsv sidecar")
    parser.add_argument("--tolerance", type=int, default=10)
    parser.add_argument("--total-queries", type=int, default=0)
    args = parser.parse_args()

    truth = load_truth(args.truth)

    dctx = zstandard.ZstdDecompressor()
    with open(args.queries_file, "rb") as f:
        with dctx.stream_reader(f) as reader:
            raw = reader.read()
    # QueryIndex = HashMap<String, Vec<(u32, f64)>>; msgpack decodes tuples as lists.
    data: dict = msgpack.unpackb(raw, raw=False)

    n_mapped = len(data)
    n_parseable = 0
    n_correct = 0

    for query_name, alignments in data.items():
        # provenance/query id is the full FASTA header (see compute_indel_recovery.py) —
        # take the leading whitespace-delimited token to match truth.tsv's bare query_id.
        query_id = query_name.split(" ", 1)[0]
        true_start = truth.get(query_id)
        if true_start is None:
            continue  # not in our own generated truth set — can't evaluate
        if not alignments:
            continue
        n_parseable += 1
        best_pos = int(max(alignments, key=lambda x: x[1])[0])
        if abs(best_pos - true_start) <= args.tolerance:
            n_correct += 1

    pa = n_correct / n_parseable if n_parseable > 0 else 0.0

    total = args.total_queries if args.total_queries > 0 else n_mapped
    n_unaligned = max(0, total - n_mapped)
    unaligned_frac = n_unaligned / total if total > 0 else 0.0

    print(f"{pa:.4f}\t{n_mapped}\t{n_correct}\t{n_unaligned}\t{unaligned_frac:.4f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
